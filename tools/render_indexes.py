#!/usr/bin/env python3
"""Render the navigation indexes: a README.md for explanation/, each of its
directories, technical/, technical/design/ and reference/.

The pages are generated. Reading order comes from the publication manifest;
everything else comes from the registry. They restate nothing that is not in
one of the two, so there is no second list to keep in step by hand.

Run with --check to fail when a page on disk is out of date.
"""

from __future__ import annotations

import argparse
import posixpath
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent / "publication"))
from model import load_manifest, sections  # noqa: E402
from projection import H1_RE, table  # noqa: E402
from validate_registry import ROOT, as_list, load_registry, parse_reference  # noqa: E402

NOTICE = "Generated by `tools/render_indexes.py` from the publication manifest and the registry. Do not edit."
OPEN_FINDINGS = ("open", "issue_opened")


def title_of(rel: str, docs_root: Path) -> str:
    match = H1_RE.search((docs_root / rel).read_text(encoding="utf-8"))
    return match.group(1) if match else rel


def render(docs_root: Path = ROOT) -> dict[str, str]:
    """Every index page, keyed by its path in the repository."""
    reg = load_registry(docs_root / "registry")
    manifest = load_manifest(docs_root / "publication" / "publications" / "biopeia-master.yaml", docs_root)
    units, findings, domains = reg["coverage"], reg["findings"], reg["schema"]["domains"]
    ordered = [rel for s in sections(manifest) for rel in s.get("chapters") or [] if rel.startswith("explanation/")]
    directories = list(dict.fromkeys(rel.split("/")[1] for rel in ordered))
    pages: dict[str, str] = {}

    def page(path: str, heading: str, body: list[str]) -> None:
        def link(target: str, text: str | None = None) -> str:
            return f"[{text or target}]({posixpath.relpath(target, posixpath.dirname(path))})"

        lines = [f"# {heading}", "", NOTICE, ""]
        for item in body:
            lines += item(link) if callable(item) else [item]
        pages[path] = "\n".join(lines).rstrip() + "\n"

    # --- explanation/<directory>/README.md ------------------------------------
    for directory in directories:
        docs = [rel for rel in ordered if rel.split("/")[1] == directory]
        mine = {uid: u for uid, u in units.items() if set(as_list(u.get("canonical_docs"))) & set(docs)}
        owner_domains = sorted({u["owner_domain"] for u in mine.values()})
        nature = f" ({domains[directory]['nature']})" if directory in domains else ""
        purpose = (
            f"Explanatory documents of the {directory.capitalize()} domain{nature}."
            if directory in domains
            else "Explanations that cross domains. They are derived from the unit documents and add no fact of their own."
        )

        def body(link, docs=docs, mine=mine, owner_domains=owner_domains, directory=directory, purpose=purpose):
            out = ["## Purpose", "", purpose, "", "## Start here", "", link(docs[0], title_of(docs[0], docs_root)), ""]
            out += ["## Reading order", ""]
            out += [f"{n}. {link(rel, title_of(rel, docs_root))}" for n, rel in enumerate(docs, start=1)] + [""]

            out += ["## Canonical documents", ""]
            rows = []
            for uid, unit in mine.items():
                for rel in as_list(unit["canonical_docs"]):
                    if rel in docs:
                        review = unit.get("review", {}).get("status", "not recorded")
                        rows.append([link(rel, posixpath.basename(rel)), f"`{uid}`", unit["status"], review])
            out += table(["Document", "Unit", "Status", "Review"], rows)

            out += ["## Related domains", ""]
            related = []
            for contract in reg["contracts"].values():
                parties = {units.get(p["unit"], {}).get("owner_domain") for p in contract["parties"]}
                if any(p["unit"] in mine for p in contract["parties"]):
                    others = sorted(d for d in parties if d and d not in owner_domains)
                    related.append(f"- {contract['title']}: with {', '.join(others) or 'no other domain'}")
            out += (related or ["No cross-domain contract registered for these units."]) + [""]

            out += ["## Designs", ""]
            designs = [
                f"- {link(d['path'], d['title'])}: document {d['document_status']}, "
                f"implementation {d['implementation_status']}, scope {d['architecture_scope']}"
                for d in reg["designs"].values()
                if directory == d["domain"] or directory in as_list(d.get("participating_domains"))
            ]
            out += (designs or ["No design registered for this domain."]) + [""]

            out += ["## Decision records", ""]
            decisions = sorted({ref for u in mine.values() for ref in as_list(u.get("adrs"))})
            decision_lines = []
            for ref in decisions:
                repo, rel = parse_reference(ref)
                decision_lines.append(f"- {link(rel, title_of(rel, docs_root))}" if repo == "docs" else f"- `{ref}`")
            out += (decision_lines or ["No decision record cited by these units."]) + [""]

            out += ["## Open findings", ""]
            still = [f for f in findings.values() if f["status"] in OPEN_FINDINGS and set(as_list(f.get("units"))) & set(mine)]
            if still:
                counts = Counter(f["class"] for f in still)
                with_issue = sum(1 for f in still if f.get("issue"))
                out += [f"{len(still)} findings on these units are open, {with_issue} of them with an issue in the owning repository:", ""]
                out += [f"- {name.replace('_', ' ')}: {count}" for name, count in sorted(counts.items())]
                out += ["", f"They are recorded in {link('registry/findings.yaml')} and listed per unit in {link('reference/units.md')}.", ""]
            else:
                out += ["No open finding on these units.", ""]
            return out

        page(f"explanation/{directory}/README.md", directory.capitalize(), [body])

    # --- explanation/README.md -------------------------------------------------
    def explanation(link):
        out = ["## Purpose", "", "How Biopeia works, traced to code, tests and decisions. Each directory has its own index.", ""]
        out += ["## Start here", "", link(ordered[0], title_of(ordered[0], docs_root)), ""]
        out += ["## Reading order", "", f"The order of the main publication, set in {link('publication/publications/biopeia-master.yaml')}.", ""]
        number = 0
        for section in manifest["parts"]:
            chapters = [rel for rel in section.get("chapters") or [] if rel.startswith("explanation/")]
            indexes = list(dict.fromkeys(f"explanation/{rel.split('/')[1]}/README.md" for rel in chapters))
            number += 1
            where = ", ".join(link(i, i.split("/")[1]) for i in indexes) or "no explanatory document yet"
            out.append(f"{number}. {section['title']}: {where}" if not chapters else f"{number}. {section['title']}: {len(chapters)} document{'s' * (len(chapters) != 1)} ({where})")
        return out + [""]

    page("explanation/README.md", "Explanation", [explanation])

    # --- technical/ --------------------------------------------------------------
    def technical(link):
        records = sorted((docs_root / "technical" / "adr").glob("ADR-*.md"))
        return [
            "## Purpose", "",
            "Decision records and design documents. Recording one here does not accept it.", "",
            "## Contents", "",
            f"- {link('technical/adr/README.md', 'Decision records')}: {len(records)} records",
            f"- {link('technical/design/README.md', 'Designs')}: {len(reg['designs'])} designs", "",
            f"- {link('technical/decision-notes/README.md', 'Decision Notes')}: local and reversible decisions",
            f"- {link('technical/templates/procedure/design.md', 'Procedure templates')}: design, ADR, and DN", "",
        ]

    page("technical/README.md", "Technical documentation", [technical])

    def designs(link):
        rows = [
            [link(d["path"], d["title"]), d["domain"], d["document_status"], d["implementation_status"], d["architecture_scope"]]
            for d in reg["designs"].values()
        ]
        return [
            "## Purpose", "",
            f"Design documents. Their state lives only in {link('registry/designs.yaml')}; the three",
            "states are independent, and an approved design is never, by that fact, an implemented one.", "",
            "## Designs", "",
            *table(["Design", "Domain", "Document", "Implementation", "Architecture scope"], rows),
        ]

    page("technical/design/README.md", "Designs", [designs])

    # --- reference/ --------------------------------------------------------------
    def reference(link):
        files = sorted(p.name for p in (docs_root / "reference").glob("*.md") if p.name != "README.md")
        return ["## Purpose", "", "Pages for looking something up.", "", "## Contents", "",
                *[f"- {link(f'reference/{name}', title_of(f'reference/{name}', docs_root))}" for name in files], ""]

    page("reference/README.md", "Reference", [reference])

    # --- how-to/ -----------------------------------------------------------------
    if (docs_root / "how-to").is_dir():
        def how_to(link):
            files = sorted(p.relative_to(docs_root / "how-to").as_posix()
                           for p in (docs_root / "how-to").rglob("*.md") if p.name != "README.md")
            return [
                "## Purpose", "",
                "Task-oriented, step-by-step procedures for operators, developers, and researchers.", "",
                "## Guides", "",
                *[f"- {link(f'how-to/{name}', title_of(f'how-to/{name}', docs_root))}" for name in files], "",
            ]

        page("how-to/README.md", "How-to Guides", [how_to])

    # --- tutorials/ --------------------------------------------------------------
    if (docs_root / "tutorials").is_dir():
        def tutorials(link):
            files = sorted(p.relative_to(docs_root / "tutorials").as_posix()
                           for p in (docs_root / "tutorials").rglob("*.md") if p.name != "README.md")
            return [
                "## Purpose", "",
                "Guided, executable learning experiences starting from verified baselines.", "",
                "## Tutorials", "",
                *[f"- {link(f'tutorials/{name}', title_of(f'tutorials/{name}', docs_root))}" for name in files], "",
            ]

        page("tutorials/README.md", "Tutorials", [tutorials])

    return pages


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a page on disk is out of date")
    args = parser.parse_args(argv)
    stale = []
    for rel, text in render().items():
        path = ROOT / rel
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            stale.append(rel)
            if not args.check:
                path.write_text(text, encoding="utf-8")
    if args.check and stale:
        print("Out of date; run tools/render_indexes.py:\n" + "\n".join(f"  {rel}" for rel in stale))
        return 1
    print(f"Navigation indexes: {'current' if args.check else f'{len(stale)} written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
